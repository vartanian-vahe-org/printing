import { renderFace, type CardGeometry, type Template } from '@printing/templates';

/**
 * A template face as inline SVG (server-rendered). Inline, not an <img>, so it uses the page's
 * template fonts (@font-face in globals.css) instead of a system fallback.
 */
export function CardArt({
  template,
  geometry,
  side = 'front',
  className,
  label,
}: {
  template: Template;
  geometry: CardGeometry;
  side?: 'front' | 'back';
  className?: string;
  /** Accessible name; decorative when omitted. */
  label?: string;
}) {
  const { svg } = renderFace({ layout: template.layout, side, values: {}, geometry });
  return (
    <span
      className={`card-art ${className ?? ''}`}
      {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true })}
      // Generated by our renderer from template data; every text value is XML-escaped.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
