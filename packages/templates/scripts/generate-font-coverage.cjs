// Generates src/font-coverage.ts: the characters each template font can draw, as code point ranges.
// Run from apps/api (it has the font packages and fontkit):
//   node ../../packages/templates/scripts/generate-font-coverage.cjs
// Re-run after changing font files or FONT_FILES.
const { readFileSync, writeFileSync } = require('node:fs');
const { dirname, join } = require('node:path');
// Resolve packages from the directory it is run in (apps/api), not from this file.
const requireFromCwd = require('node:module').createRequire(join(process.cwd(), 'package.json'));
const fontkit = requireFromCwd('@pdf-lib/fontkit');

const families = {
  sans: { pkg: '@expo-google-fonts/inter', files: ['400Regular/Inter_400Regular.ttf', '800ExtraBold/Inter_800ExtraBold.ttf'] },
  serif: { pkg: '@expo-google-fonts/lora', files: ['400Regular/Lora_400Regular.ttf', '700Bold/Lora_700Bold.ttf'] },
};

const out = {};
for (const [family, { pkg, files }] of Object.entries(families)) {
  // Characters present in every weight we checked (weights of one family share a character set).
  let common = null;
  for (const file of files) {
    const font = fontkit.create(readFileSync(join(dirname(requireFromCwd.resolve(`${pkg}/package.json`)), file)));
    const set = new Set(font.characterSet.filter((cp) => cp >= 0x20 && font.hasGlyphForCodePoint(cp)));
    common = common ? new Set([...common].filter((cp) => set.has(cp))) : set;
  }
  const points = [...common].sort((a, b) => a - b);
  const ranges = [];
  for (const cp of points) {
    const last = ranges[ranges.length - 1];
    if (last && cp === last[1] + 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  out[family] = ranges;
}

const target = join(__dirname, '..', 'src', 'font-coverage.ts');
writeFileSync(
  target,
  `/** Generated by scripts/generate-font-coverage.cjs from the template font files. Do not edit. */\n` +
    `export const FONT_COVERAGE: Record<'sans' | 'serif', [number, number][]> = ${JSON.stringify(out)};\n`,
);
console.log(`Wrote ${target}: sans ${out.sans.length} ranges, serif ${out.serif.length} ranges`);
